import { Router } from 'express';
import ctrl, { getCalendar, getOnThisDay, getRencontreDetail, getRencontreHighlights, getTourMatches, getComposition, getSquad } from '../controllers/rencontres.controller';
const router = Router();
router.get('/calendar', getCalendar);
router.get('/on-this-day', getOnThisDay);
router.get('/:id/detail', getRencontreDetail);
router.get('/:id/highlights', getRencontreHighlights);
router.get('/:id/tour-matches', getTourMatches);
router.get('/:id/composition', getComposition);
router.get('/:id/squad', getSquad);
router.get('/', ctrl.getAll);
router.get('/:id', ctrl.getById);
export default router;
